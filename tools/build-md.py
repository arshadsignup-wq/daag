#!/usr/bin/env python3
"""Write a Markdown sibling for every route: /about -> /about.md

Why this exists
---------------
Every generated HTML file contains all eleven page sections, because the site
is one SPA shell copied per route. Making the right section `active` fixed
browsers -- they apply CSS and hide the other ten -- but a text extractor that
ignores CSS still reads the homepage at every URL. Measured with trafilatura:
ten of the nineteen URLs returned byte-identical homepage text.

Rewriting the shell so each file carries only its own section would fix that
properly, and would also break client-side navigation, which is a far larger
change than the problem warrants. This is the cheaper half: a clean Markdown
rendering of each page's own content, linked from the HTML with
`rel="alternate" type="text/markdown"` and listed in llms.txt. Retrieval
crawlers get per-page text; the SPA is untouched.

The source of truth stays index.html. Nothing here is written by hand.

    python3 tools/build-md.py          # write the .md files
    python3 tools/build-md.py --check  # exit 1 if any is missing or stale
"""

import argparse
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'index.html')
POSTS_DIR = os.path.join(ROOT, 'content', 'blog')
OUT_DIR = os.path.join(ROOT, 'md')
ORIGIN = 'https://www.daag-bd.com'

STAMP = ('<!-- generated by tools/build-md.py from index.html; do not edit -->\n')

# Elements whose text is chrome, not content: the nav, the footer, the cookie
# strip, the screenshot lightbox, and the noscript fallback.
DROP_SECTIONS = re.compile(
    r'<(nav|footer|noscript)\b.*?</\1>|<div[^>]*class="[^"]*(ss-modal|cookie)[^"]*".*?</div>',
    re.S | re.I)


def page_meta(html):
    """Read PAGE_META out of index.html -- the same single source prerender uses."""
    m = re.search(r'var PAGE_META=\{(.*?)\n\};', html, re.S)
    if not m:
        sys.exit('build-md: PAGE_META not found in index.html')
    meta = {}
    for route, title, desc in re.findall(
            r"(\w+):\s*\{t:'(.*?)',\s*d:'(.*?)'\}", m.group(1)):
        meta[route] = {'t': title.replace("\\'", "'"), 'd': desc.replace("\\'", "'")}
    return meta


def routes(html):
    m = re.search(r"pages=\[(.*?)\]", html)
    if not m:
        sys.exit('build-md: pages[] not found in index.html')
    return re.findall(r"'([a-z]+)'", m.group(1))


def section(html, route):
    """The markup of one page section, without the sections that follow it."""
    m = re.search(r'<section id="pg-%s"[^>]*>(.*?)(?=<section id="pg-|</main>)'
                  % re.escape(route), html, re.S)
    if not m:
        sys.exit('build-md: #pg-%s not found' % route)
    return m.group(1)


def unescape(t):
    for a, b in (('&amp;', '&'), ('&lt;', '<'), ('&gt;', '>'), ('&quot;', '"'),
                 ('&#39;', "'"), ('&nbsp;', ' '), ('&middot;', '\u00b7')):
        t = t.replace(a, b)
    return t


def inline(frag):
    """Links survive as Markdown; every other tag is dropped."""
    frag = re.sub(r'<a\b[^>]*href="([^"]*)"[^>]*>(.*?)</a>',
                  lambda m: '[%s](%s)' % (re.sub(r'<[^>]+>', '', m.group(2)).strip(),
                                          m.group(1)), frag, flags=re.S)
    frag = re.sub(r'<(strong|b)\b[^>]*>(.*?)</\1>',
                  lambda m: '**%s**' % re.sub(r'<[^>]+>', '', m.group(2)).strip(),
                  frag, flags=re.S)
    frag = re.sub(r'<[^>]+>', ' ', frag)
    return re.sub(r'[ \t]+', ' ', unescape(frag)).strip()


def to_markdown(frag):
    frag = DROP_SECTIONS.sub(' ', frag)
    frag = re.sub(r'<(script|style|svg)\b.*?</\1>', ' ', frag, flags=re.S | re.I)
    out, seen = [], set()
    token = re.compile(r'<(h[1-6])\b[^>]*>(.*?)</\1>'
                       r'|<li\b[^>]*>(.*?)</li>'
                       r'|<(?:p|q)\b[^>]*>(.*?)</(?:p|q)>'
                       r'|<div[^>]*class="[^"]*(?:faq-a-inner|sub2|eyebrow|lede-p)[^"]*"[^>]*>(.*?)</div>',
                       re.S | re.I)
    for m in token.finditer(frag):
        if m.group(1):
            text = inline(m.group(2))
            if text:
                # demoted one level: the document's own h1 is the page title
                # written above, so the section's h1 becomes h2 and so on.
                depth = min(int(m.group(1)[1]) + 1, 6)
                out.append('%s %s' % ('#' * depth, text))
        elif m.group(3) is not None:
            text = inline(m.group(3))
            if text:
                out.append('- %s' % text)
        else:
            text = inline(m.group(4) if m.group(4) is not None else m.group(5))
            if text and text not in seen:
                out.append(text)
                seen.add(text)
    # collapse runs of blank entries, keep one blank line between blocks
    body = '\n\n'.join(x for x in out if x)
    return re.sub(r'\n{3,}', '\n\n', body).strip()


def render_route(html, route, meta):
    url = ORIGIN + ('/' if route == 'home' else '/' + route)
    body = to_markdown(section(html, route))
    if len(body) < 40:
        sys.exit('build-md: %s rendered only %d chars, refusing to ship'
                 % (route, len(body)))
    return '%s# %s\n\n> %s\n>\n> Source: %s\n\n%s\n' % (
        STAMP, meta['t'].split('|')[0].strip(), meta['d'], url, body)


def post_markdown(path):
    """A post already is Markdown. Serve its body, not the front matter."""
    raw = io.open(path, encoding='utf-8').read()
    m = re.match(r'---\n(.*?)\n---\n(.*)', raw, re.S)
    if not m:
        sys.exit('build-md: %s has no front matter' % path)
    front, body = m.group(1), m.group(2).strip()
    def field(name):
        f = re.search(r'^%s:\s*(.*)$' % name, front, re.M)
        return f.group(1).strip().strip('"\'') if f else ''
    slug = os.path.basename(path)[:-3]
    return '%s# %s\n\n> %s\n>\n> Source: %s/blog/%s\n\n%s\n' % (
        STAMP, field('title'), field('description'), ORIGIN, slug, body)


def write(path, text, check, stale, wrote):
    old = io.open(path, encoding='utf-8').read() if os.path.exists(path) else None
    if old == text:
        return
    if check:
        stale.append(os.path.relpath(path, ROOT))
        return
    io.open(path, 'w', encoding='utf-8').write(text)
    wrote.append('%-28s %5d chars' % (os.path.relpath(path, ROOT), len(text)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()

    html = io.open(SRC, encoding='utf-8').read()
    meta = page_meta(html)
    stale, wrote = [], []

    if not args.check:
        os.makedirs(os.path.join(OUT_DIR, 'blog'), exist_ok=True)

    for route in routes(html):
        if route not in meta:
            sys.exit('build-md: %s is in pages[] but not in PAGE_META' % route)
        name = 'index.md' if route == 'home' else route + '.md'
        write(os.path.join(OUT_DIR, name),
              render_route(html, route, meta[route]), args.check, stale, wrote)

    posts = sorted(f for f in os.listdir(POSTS_DIR) if f.endswith('.md'))
    for f in posts:
        write(os.path.join(OUT_DIR, 'blog', f),
              post_markdown(os.path.join(POSTS_DIR, f)), args.check, stale, wrote)

    # llms-full.txt: every page's text in one file, which is what a retrieval
    # crawler wants when it would otherwise fetch nineteen URLs. /llms-full.txt
    # was a 404 and agentic_check.py flags it.
    parts = ['# Daag (\u09a6\u09be\u0997) \u2014 full text\n\n'
             '> Every page of https://www.daag-bd.com in one file. Generated by\n'
             '> tools/build-md.py; the site itself is the source of truth.\n'
             '>\n'
             '> The archive entries themselves are not included: they are served from\n'
             '> a database, change constantly, and can be withdrawn on appeal. Read\n'
             '> them at https://www.daag-bd.com/archive.']
    for route in routes(html):
        name = 'index.md' if route == 'home' else route + '.md'
        parts.append(io.open(os.path.join(OUT_DIR, name), encoding='utf-8')
                     .read().replace(STAMP, '').strip())
    for f in posts:
        parts.append(io.open(os.path.join(OUT_DIR, 'blog', f), encoding='utf-8')
                     .read().replace(STAMP, '').strip())
    write(os.path.join(ROOT, 'llms-full.txt'),
          '\n\n---\n\n'.join(parts) + '\n', args.check, stale, wrote)

    if args.check:
        if stale:
            print('STALE, run python3 tools/build-md.py:')
            for f in stale:
                print('   ', f)
            return 1
        print('build-md: %d markdown sibling(s), all up to date'
              % (len(routes(html)) + len(posts)))
        return 0

    for line in wrote:
        print('  ' + line)
    print('build-md: %d file(s) written' % len(wrote) if wrote
          else 'build-md: already up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
