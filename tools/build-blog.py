#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Turn content/blog/*.md into the blog index and one page per post.

    python3 tools/build-blog.py            # rebuild
    python3 tools/build-blog.py --check    # fail if output is stale

Posts are Markdown with YAML-ish front matter. Each one becomes
`blog/<slug>.html`, built from index.html so it carries the real nav, footer,
theming, language toggle and head tags, exactly like the route files that
tools/prerender.py produces. The blog index lives at `blog.html`.

Run this BEFORE tools/prerender.py: this writes the post list into the
`#pg-blog` section of index.html, and prerender then copies index.html out to
the other routes.

Nothing here invents content. The Markdown is the source; every external link
in a post was fetched and checked before publication, and the figures are
attributed in the prose itself.
"""
import argparse
import html
import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'index.html')
POSTS_DIR = os.path.join(ROOT, 'content', 'blog')
OUT_DIR = os.path.join(ROOT, 'blog')
ORIGIN = 'https://www.daag-bd.com'
STAMP = '<!-- generated by tools/build-blog.py from content/blog/; do not edit -->'


def parse_post(path):
    raw = io.open(path, encoding='utf-8').read()
    m = re.match(r'^---\n(.*?)\n---\n(.*)$', raw, re.S)
    if not m:
        sys.exit('build-blog: %s has no front matter' % os.path.basename(path))
    meta, body = {}, m.group(2).strip()
    for line in m.group(1).split('\n'):
        if not line.strip() or line.startswith(' '):
            continue
        k, _, v = line.partition(':')
        v = v.strip()
        if v.startswith('"') and v.endswith('"'):
            v = v[1:-1]
        if v.startswith('[') and v.endswith(']'):
            v = [x.strip() for x in v[1:-1].split(',') if x.strip()]
        meta[k.strip()] = v
    for required in ('slug', 'title', 'description', 'date', 'author'):
        if required not in meta:
            sys.exit('build-blog: %s is missing %s' % (os.path.basename(path), required))
    meta['body'] = body
    return meta


def md(text):
    """Enough Markdown for these posts, and nothing more.

    Deliberately small: headings, tables, lists, links, bold, hr, paragraphs.
    A general-purpose parser is not worth the dependency for prose we write
    ourselves, and a small one is auditable.
    """
    out, lines, i = [], text.split('\n'), 0

    def inline(s):
        s = html.escape(s, quote=False)
        s = re.sub(r'\[([^\]]+)\]\((https?://[^)\s]+)\)',
                   r'<a href="\2" target="_blank" rel="noopener noreferrer">\1</a>', s)
        s = re.sub(r'\[([^\]]+)\]\((/[^)\s]*)\)', r'<a href="\2">\1</a>', s)
        s = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', s)
        s = re.sub(r'(?<![\w*])\*([^*\n]+)\*(?![\w*])', r'<em>\1</em>', s)
        return s

    while i < len(lines):
        ln = lines[i]
        if not ln.strip():
            i += 1
            continue
        if ln.startswith('---'):
            out.append('<hr>')
            i += 1
            continue
        h = re.match(r'^(#{2,4})\s+(.*)$', ln)
        if h:
            lvl = len(h.group(1))
            out.append('<h%d class="bp-h%d">%s</h%d>' % (lvl, lvl, inline(h.group(2)), lvl))
            i += 1
            continue
        if ln.lstrip().startswith('|'):
            rows = []
            while i < len(lines) and lines[i].lstrip().startswith('|'):
                rows.append([c.strip() for c in lines[i].strip().strip('|').split('|')])
                i += 1
            if len(rows) >= 2 and set(''.join(rows[1])) <= set('-: '):
                head, body_rows = rows[0], rows[2:]
            else:
                head, body_rows = None, rows
            t = ['<div class="bp-tablewrap"><table class="bp-table">']
            if head:
                t.append('<thead><tr>' + ''.join('<th>%s</th>' % inline(c) for c in head) + '</tr></thead>')
            t.append('<tbody>')
            for r in body_rows:
                t.append('<tr>' + ''.join('<td>%s</td>' % inline(c) for c in r) + '</tr>')
            t.append('</tbody></table></div>')
            out.append(''.join(t))
            continue
        if re.match(r'^\s*\d+\.\s+', ln) or re.match(r'^\s*[-*]\s+', ln):
            ordered = bool(re.match(r'^\s*\d+\.\s+', ln))
            items = []
            while i < len(lines) and (re.match(r'^\s*\d+\.\s+', lines[i]) or re.match(r'^\s*[-*]\s+', lines[i])):
                items.append(re.sub(r'^\s*(?:\d+\.|[-*])\s+', '', lines[i]))
                i += 1
            tag = 'ol' if ordered else 'ul'
            out.append('<%s class="bp-list">%s</%s>'
                       % (tag, ''.join('<li>%s</li>' % inline(x) for x in items), tag))
            continue
        para = []
        while i < len(lines) and lines[i].strip() and not re.match(r'^(#{2,4}\s|\s*[-*]\s|\s*\d+\.\s|\|)', lines[i]) \
                and not lines[i].startswith('---'):
            para.append(lines[i])
            i += 1
        out.append('<p>%s</p>' % inline(' '.join(para)))
    return '\n'.join(out)


def fmt_date(iso):
    y, m, d = iso.split('-')
    months = ['January', 'February', 'March', 'April', 'May', 'June', 'July',
              'August', 'September', 'October', 'November', 'December']
    return '%d %s %s' % (int(d), months[int(m) - 1], y)


def esc(s):
    return html.escape(str(s), quote=True)


def article_schema(post):
    return json.dumps({
        "@context": "https://schema.org", "@type": "Article",
        "headline": post['title'],
        "description": post['description'],
        "datePublished": post['date'],
        "dateModified": post['date'],
        "inLanguage": "en",
        "author": {"@type": "Organization", "name": post['author'],
                   "url": ORIGIN + "/about"},
        "publisher": {"@id": ORIGIN + "/#organization"},
        "isPartOf": {"@type": "Blog", "name": "Daag", "url": ORIGIN + "/blog"},
        "mainEntityOfPage": {"@type": "WebPage",
                             "@id": '%s/blog/%s' % (ORIGIN, post['slug'])},
    }, ensure_ascii=False, separators=(',', ':'))


def set_tag(doc, pattern, replacement):
    new, n = re.subn(pattern, lambda _: replacement, doc, count=1)
    if n != 1:
        sys.exit('build-blog: expected one match for %s, got %d' % (pattern[:40], n))
    return new


def build_post_page(shell, post):
    url = '%s/blog/%s' % (ORIGIN, post['slug'])
    title = '%s | Daag' % post['title']
    doc = shell
    doc = set_tag(doc, r'<title>.*?</title>', '<title>%s</title>' % esc(title))
    doc = set_tag(doc, r'<meta name="description" content="[^"]*">',
                  '<meta name="description" content="%s">' % esc(post['description']))
    doc = set_tag(doc, r'<link rel="canonical" href="[^"]*">',
                  '<link rel="canonical" href="%s">' % url)
    doc = set_tag(doc, r'<meta property="og:title" content="[^"]*">',
                  '<meta property="og:title" content="%s">' % esc(post['title']))
    doc = set_tag(doc, r'<meta property="og:description" content="[^"]*">',
                  '<meta property="og:description" content="%s">' % esc(post['description']))
    doc = set_tag(doc, r'<meta property="og:url" content="[^"]*">',
                  '<meta property="og:url" content="%s">' % url)
    doc = set_tag(doc, r'<meta property="og:type" content="[^"]*">',
                  '<meta property="og:type" content="article">')
    doc = set_tag(doc, r'<meta name="twitter:title" content="[^"]*">',
                  '<meta name="twitter:title" content="%s">' % esc(post['title']))
    doc = set_tag(doc, r'<meta name="twitter:description" content="[^"]*">',
                  '<meta name="twitter:description" content="%s">' % esc(post['description']))

    bn = post.get('lede_bn', '')
    article = (
        '  <article class="bp" id="bp-%s">\n'
        '    <div class="section-sm" style="padding-top:3rem;padding-bottom:1rem">\n'
        '      <a class="bp-back" href="/blog">&larr; <span data-i18n="blog.all">All posts</span></a>\n'
        '      <h1 class="bp-title">%s</h1>\n'
        '      <div class="bp-meta"><span>%s</span><span aria-hidden="true">&middot;</span>'
        '<span>%s</span></div>\n'
        '%s'
        '    </div>\n'
        '    <div class="section-sm bp-body" style="padding-top:0">\n%s\n    </div>\n'
        '  </article>'
    ) % (
        esc(post['slug']), esc(post['title']), esc(post['author']), fmt_date(post['date']),
        ('      <p class="bp-lede" lang="bn">%s</p>\n' % esc(bn)) if bn else '',
        md(post['body']),
    )

    doc = re.sub(r'(<section id="pg-blog" class="page">)(.*?)(</section>)',
                 lambda m: m.group(1) + '\n' + article + '\n' + m.group(3),
                 doc, count=1, flags=re.S)
    doc = doc.replace('</head>', '<script type="application/ld+json">%s</script>\n%s\n</head>'
                      % (article_schema(post), STAMP), 1)
    return doc


def build_index_section(posts):
    cards = []
    for p in posts:
        cards.append(
            '      <li class="bl-item"><a href="/blog/%s">\n'
            '        <span class="bl-date">%s</span>\n'
            '        <span class="bl-title">%s</span>\n'
            '        <span class="bl-desc">%s</span>\n'
            '      </a></li>' % (esc(p['slug']), fmt_date(p['date']),
                                 esc(p['title']), esc(p['description'])))
    return (
        '  <div style="background:var(--bg1);border-bottom:1px solid var(--border)">\n'
        '    <div class="section-sm" style="padding-top:3.5rem;padding-bottom:3.5rem">\n'
        '      <div data-i18n="blog.tag" class="section-tag">Writing</div>\n'
        '      <h2 data-i18n="blog.title" class="section-title">From the archive</h2>\n'
        '      <p data-i18n="blog.intro" style="color:var(--text2);max-width:62ch;line-height:1.8;'
        'font-size:14px;margin-top:.5rem">What the record shows, what the courts decided, and how to '
        'document a comment so it holds up. Every figure links to the report it came from.</p>\n'
        '    </div>\n'
        '  </div>\n'
        '  <div class="section-sm" style="padding-top:2.4rem">\n'
        '    <ol class="bl-list">\n%s\n    </ol>\n  </div>' % '\n'.join(cards))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()

    if not os.path.isdir(POSTS_DIR):
        sys.exit('build-blog: %s does not exist' % POSTS_DIR)
    posts = [parse_post(os.path.join(POSTS_DIR, f))
             for f in sorted(os.listdir(POSTS_DIR)) if f.endswith('.md')]
    if not posts:
        sys.exit('build-blog: no posts found')
    posts.sort(key=lambda p: p['date'], reverse=True)

    slugs = [p['slug'] for p in posts]
    if len(set(slugs)) != len(slugs):
        sys.exit('build-blog: duplicate slug')

    shell = io.open(SRC, encoding='utf-8').read()
    if '<section id="pg-blog" class="page">' not in shell:
        sys.exit('build-blog: index.html has no #pg-blog section')

    # 1. the index listing, written back into index.html
    new_shell = re.sub(r'(<section id="pg-blog" class="page">)(.*?)(</section>)',
                       lambda m: m.group(1) + '\n' + build_index_section(posts) + '\n' + m.group(3),
                       shell, count=1, flags=re.S)
    stale = []
    if new_shell != shell:
        if args.check:
            stale.append('index.html (blog list)')
        else:
            io.open(SRC, 'w', encoding='utf-8').write(new_shell)
    shell = new_shell

    # 2. one page per post
    if not args.check:
        os.makedirs(OUT_DIR, exist_ok=True)
    written = []
    for p in posts:
        page = build_post_page(shell, p)
        path = os.path.join(OUT_DIR, p['slug'] + '.html')
        old = io.open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old == page:
            continue
        if args.check:
            stale.append('blog/%s.html' % p['slug'])
            continue
        io.open(path, 'w', encoding='utf-8').write(page)
        written.append(p)

    if args.check:
        if stale:
            print('STALE, run python3 tools/build-blog.py:')
            for s in stale:
                print('   ', s)
            return 1
        print('build-blog: %d post(s), all up to date' % len(posts))
        return 0

    for p in written:
        words = len(re.sub(r'<[^>]+>', ' ', p['body']).split())
        print('  %-52s %s  %4d words' % (p['slug'][:52], p['date'], words))
    print('build-blog: %d post(s), %d written' % (len(posts), len(written)))
    print('  now run: python3 tools/prerender.py')
    return 0


if __name__ == '__main__':
    sys.exit(main())
