#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Write one HTML file per route, with that route's own head tags baked in.

    python3 tools/prerender.py           # regenerate
    python3 tools/prerender.py --check   # fail if the files are stale

Why this exists
---------------
The site is one HTML file served at every URL. Title, description and canonical
were rewritten by JavaScript after load, which meant the HTML actually served
for /archive, /about and seven other routes carried the homepage's title, the
homepage's description, and a canonical pointing at the homepage. A canonical
pointing somewhere else is not a hint, it is an instruction to consolidate, so
nine pages were telling Google they were duplicates of the tenth.

Google renders JavaScript and may honour the corrected tags. Nothing else does:
every social scraper and most retrieval crawlers read the served bytes only.

So each route gets a real file. vercel.json rewrites /archive to /archive.html
and so on. The runtime JS is untouched and still updates the head on client-side
navigation, which is correct for people clicking around; this only fixes the
first byte a crawler sees.

PAGE_META inside index.html stays the single source of truth for every title and
description. Nothing is duplicated here, it is read back out.

Run this after editing index.html. `--check` is the guard against forgetting.
"""
import argparse
import hashlib
import io
import json
import os
import re
import sys
from html.parser import HTMLParser

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'index.html')
ORIGIN = 'https://www.daag-bd.com'
STAMP = '<!-- generated by tools/prerender.py from index.html; do not edit -->'


def page_meta(html):
    """Read PAGE_META out of index.html so titles live in exactly one place."""
    m = re.search(r'var PAGE_META=\{(.*?)\n\};', html, re.S)
    if not m:
        sys.exit('prerender: PAGE_META not found in index.html')
    out = {}
    for key, title, desc in re.findall(r"(\w+):\s*\{t:'(.*?)',\s*d:'(.*?)'\}", m.group(1)):
        out[key] = {'t': title.replace("\\'", "'"), 'd': desc.replace("\\'", "'")}
    return out


def routes(html):
    m = re.search(r"const pages=\[(.*?)\];", html)
    if not m:
        sys.exit('prerender: pages[] not found in index.html')
    return [r.strip().strip("'") for r in m.group(1).split(',')]


def set_tag(html, pattern, replacement):
    new, n = re.subn(pattern, lambda _: replacement, html, count=1)
    if n != 1:
        sys.exit('prerender: expected exactly one match for %s, got %d' % (pattern[:40], n))
    return new


def esc(s):
    return (s.replace('&', '&amp;').replace('<', '&lt;')
             .replace('>', '&gt;').replace('"', '&quot;'))


def breadcrumb(route, title):
    """A two-level trail. Only emitted for real sub-pages, never for home."""
    return json.dumps({
        "@context": "https://schema.org", "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Daag", "item": ORIGIN + '/'},
            {"@type": "ListItem", "position": 2, "name": title,
             "item": '%s/%s' % (ORIGIN, route)},
        ]}, ensure_ascii=False, separators=(',', ':'))


def build(html, route, meta):
    url = ORIGIN + ('/' if route == 'home' else '/' + route)
    title, desc = meta['t'], meta['d']
    out = html
    out = set_tag(out, r'<title>.*?</title>', '<title>%s</title>' % esc(title))
    out = set_tag(out, r'<meta name="description" content="[^"]*">',
                  '<meta name="description" content="%s">' % esc(desc))
    out = set_tag(out, r'<link rel="canonical" href="[^"]*">',
                  '<link rel="canonical" href="%s">' % url)
    out = set_tag(out, r'<meta property="og:title" content="[^"]*">',
                  '<meta property="og:title" content="%s">' % esc(title))
    out = set_tag(out, r'<meta property="og:description" content="[^"]*">',
                  '<meta property="og:description" content="%s">' % esc(desc))
    out = set_tag(out, r'<meta property="og:url" content="[^"]*">',
                  '<meta property="og:url" content="%s">' % url)
    out = set_tag(out, r'<meta name="twitter:title" content="[^"]*">',
                  '<meta name="twitter:title" content="%s">' % esc(title))
    out = set_tag(out, r'<meta name="twitter:description" content="[^"]*">',
                  '<meta name="twitter:description" content="%s">' % esc(desc))
    if route != 'home':
        out = out.replace('</head>', '<script type="application/ld+json">%s</script>\n</head>'
                          % breadcrumb(route, title), 1)
    return out.replace('</head>', STAMP + '\n</head>', 1)


class HeadCheck(HTMLParser):
    """Parse like a browser and record which tags really landed in <head>."""

    def __init__(self):
        HTMLParser.__init__(self)
        self.in_head = False
        self.head_done = False
        self.found = set()
        self.stray_text = None
        self.raw_depth = 0   # inside <script>/<style>/<title>, where text is normal

    def handle_starttag(self, tag, attrs):
        if tag in ('script', 'style', 'title'):
            self.raw_depth += 1
        if tag == 'head':
            self.in_head = True
            return
        if tag == 'body':
            self.in_head, self.head_done = False, True
            return
        if self.in_head:
            a = dict(attrs)
            key = a.get('rel') or a.get('property') or a.get('name')
            self.found.add('%s:%s' % (tag, key) if key else tag)

    def handle_endtag(self, tag):
        if tag in ('script', 'style', 'title') and self.raw_depth:
            self.raw_depth -= 1
        if tag == 'head':
            self.in_head, self.head_done = False, True

    def handle_data(self, data):
        # Text directly inside <head>, but outside <script>/<style>, is what a
        # stray '>' looks like to a parser, and it is what silently ends the
        # head.
        if self.in_head and not self.raw_depth and data.strip() \
                and self.stray_text is None:
            self.stray_text = data.strip()[:40]


def verify_head(html, label):
    """Refuse to ship a file whose head a browser would not parse as intended.

    A single doubled bracket in a meta tag once pushed the canonical, every
    og: and twitter: tag, the favicons and all the JSON-LD into <body>. It
    rendered as a 27px cream strip above the nav, which is the only reason it
    was noticed. Everything an SEO fix is for had quietly stopped working.
    """
    p = HeadCheck()
    p.feed(html)
    required = ['link:canonical', 'meta:og:title', 'meta:og:url',
                'meta:description', 'title', 'meta:twitter:card']
    missing = [r for r in required if r not in p.found]
    if p.stray_text:
        sys.exit('prerender: %s has stray text in <head> (%r). A tag is '
                 'malformed and the head ends early.' % (label, p.stray_text))
    if missing:
        sys.exit('prerender: %s is missing from <head> in %s. A tag above them '
                 'is probably malformed.' % (', '.join(missing), label))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true',
                    help='exit 1 if any generated file is missing or stale')
    args = ap.parse_args()

    html = io.open(SRC, encoding='utf-8').read()
    verify_head(html, 'index.html')
    meta = page_meta(html)
    stale, wrote = [], []

    for route in routes(html):
        if route == 'home':
            continue  # / is served by index.html itself
        if route not in meta:
            sys.exit('prerender: %s is in pages[] but not in PAGE_META' % route)
        built = build(html, route, meta[route])
        verify_head(built, route + '.html')
        path = os.path.join(ROOT, route + '.html')
        old = io.open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old == built:
            continue
        if args.check:
            stale.append(route + '.html')
            continue
        io.open(path, 'w', encoding='utf-8').write(built)
        wrote.append('%-14s %-52s %3d/%3d chars' % (
            route + '.html', meta[route]['t'][:52],
            len(meta[route]['t']), len(meta[route]['d'])))

    if args.check:
        if stale:
            print('STALE, run python3 tools/prerender.py:')
            for f in stale:
                print('   ', f)
            return 1
        print('prerender: all route files match index.html')
        return 0

    for line in wrote:
        print('  ' + line)
    print('prerender: %d file(s) written' % len(wrote) if wrote
          else 'prerender: already up to date')

    over = [(r, m) for r, m in meta.items() if len(m['t']) > 60 or len(m['d']) > 155]
    for r, m in over:
        print('  WARNING %s: title %d (max 60), description %d (max 155)'
              % (r, len(m['t']), len(m['d'])))
    return 0


if __name__ == '__main__':
    sys.exit(main())
